import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent  # package root
SRC = ROOT / "regmap" / "regmap.yaml"          # register map source
OUT = ROOT / "generated"                       # output folder

WORDS = {"u16": 1, "i16": 1, "u32": 2, "i32": 2, "f32": 2}  # regs per data type
RANGE = {"u16": (0, 0xFFFF), "i16": (-0x8000, 0x7FFF),      # value limits per integer type
         "u32": (0, 0xFFFFFFFF), "i32": (-0x80000000, 0x7FFFFFFF)}
BANNER = "GENERATED by tools/gen_regmap.py from regmap/regmap.yaml. Do not edit."  # first line of every generated file

class MapError(Exception):
    """raised when register map source is invalid."""
    pass

def load():
    """load register map source."""
    with open(SRC, encoding="utf-8") as f:
        return yaml.safe_load(f)

# ------------------------------------------------------------------ expansion
def node_layout(m):
    """validate per-node template and return derived constants."""
    n = m["node"]
    used = {}

    def claim(table, addr, words, what):
        """mark span of regs as used; raise MapError on overlap."""
        for a in range(addr, addr + words):
            key = (table, a)
            if key in used:
                raise MapError(f"{table} {a}: {what} overlaps {used[key]}")
            used[key] = what

    for h in n["health"]:
        claim("IR", h["addr"], WORDS[h["type"]], f"HLTH.{h['name']}")
        if not (h["addr"] + WORDS[h["type"]] <= n["point_base"] or n["slow_base"] <= h["addr"] < n["energy_base"]):
            raise MapError(f"HLTH.{h['name']} lies in neither the header nor the slow block")
    if n["point_base"] != sum(WORDS[h["type"]] for h in n["health"] if h["addr"] < n["point_base"]):
        raise MapError("the header before point_base has an unused register")
    max_points = max(len(x["points"]) for x in m["nodes"])
    block = n["point_block"]
    for f in n["point_fields"]:
        if f["offset"] + WORDS[f["type"]] > block:
            raise MapError(f"point field {f['qty']} exceeds the {block}-register block")
    for p in range(max_points):
        base = n["point_base"] + p * block
        for f in n["point_fields"]:
            claim("IR", base + f["offset"], WORDS[f["type"]], f"point {p} {f['qty']}")
        claim("IR", n["energy_base"] + 2 * p, 2, f"point {p} E")
        if base + block > n["slow_base"]:
            raise MapError(f"point {p} runs into the slow block")
    for h in n["holding"]:
        claim("HR", h["addr"], WORDS[h["type"]], h["name"])
    for ch in range(n["cal_channels"]):
        for f in n["cal_fields"]:
            claim("HR", n["cal_base"] + 4 * ch + f["offset"], 2, f"CAL ch {ch} {f['name']}")
    if n["cal_channels"] < 2 * max_points:
        raise MapError("cal_channels is smaller than two channels per point")
    addrs = [x["address"] for x in m["nodes"]] + [m["lcu"]["address"]]
    if len(set(addrs)) != len(addrs) or not all(1 <= a <= 247 for a in addrs):
        raise MapError("slave addresses must be unique and within 1 to 247")
    return max_points

def fast_read_count(m, node):
    """return number of input regs requested from one node during 10 Hz read (FC 04)."""
    n = m["node"]
    return n["point_base"] + n["point_block"] * len(node["points"])

def slow_read_count(m, node):
    """return number of input regs requested from one node during 1 Hz read (FC 04): {starts @ IR slow_base, ends @ last energy counter}."""
    n = m["node"]
    return n["energy_base"] - n["slow_base"] + 2 * len(node["points"])

def tags(m):
    """return list of every published tag w/ slave, table, address."""
    n = m["node"]
    out = []
    for node in m["nodes"]:
        a = node["address"]
        for h in n["health"]:
            out.append(dict(tag=f"{node['name']}.HLTH.{h['name']}", node=node["id"], slave=a,
                            segment="seg1", table="IR", addr=h["addr"], type=h["type"], scale=1,
                            unit=h.get("unit", ""), rate_hz=h["rate_hz"], mp=None, desc=h["desc"]))
        for i, p in enumerate(node["points"]):
            base = n["point_base"] + i * n["point_block"]
            for f in n["point_fields"]:
                if p["kind"] == "dc" and f.get("ac_only"):
                    continue
                qty = f["qty"]
                if p["kind"] == "dc":
                    qty = {"VRMS": "VDC", "IRMS": "IDC"}.get(qty, qty)
                out.append(dict(tag=f"{node['name']}.{p['name']}.{qty}", node=node["id"], slave=a,
                                segment="seg1", table="IR", addr=base + f["offset"], type=f["type"],
                                scale=f.get("scale", 1), unit=f["unit"], rate_hz=10, mp=p["mp"],
                                desc=f["desc"]))
            e = n["energy_field"]
            out.append(dict(tag=f"{node['name']}.{p['name']}.E", node=node["id"], slave=a,
                            segment="seg1", table="IR", addr=n["energy_base"] + 2 * i, type=e["type"],
                            scale=e["scale"], unit=e["unit"], rate_hz=e["rate_hz"], mp=p["mp"],
                            desc=e["desc"]))
    lcu = m["lcu"]
    for table, rows in (("HR", lcu["holding"]), ("IR", lcu["input"])):
        for r in rows:
            out.append(dict(tag=r["tag"], node="LCU", slave=lcu["address"], segment="seg2",
                            table=table, addr=r["addr"], type=r["type"], scale=1, unit="",
                            rate_hz=r.get("rate_hz", 0), mp=None, desc=r["desc"]))
    names = [t["tag"] for t in out]
    dup = {x for x in names if names.count(x) > 1}
    if dup:
        raise MapError(f"duplicate tags: {sorted(dup)}")
    return out

# ----------------------------------------------------------------- bus budget
def txn_seconds(nreg, seg):
    """return duration of one FC 04 transaction of nreg regs on segment (s)."""
    char = seg["bits_per_char"] / seg["baud"]
    return (8 + 5 + 2 * nreg + 2 * 3.5) * char

def bus_budget(m, branches=None):
    """return read times per node, poll cycle time, and bus utilization of seg 1."""
    seg = m["segments"]["seg1"]
    nodes = m["nodes"] if branches is None else m["nodes"][:1 + branches]
    rows, fast, slow = [], 0.0, 0.0
    for node in nodes:
        nfast = fast_read_count(m, node)
        nslow = slow_read_count(m, node)
        t_fast, t_slow = txn_seconds(nfast, seg), txn_seconds(nslow, seg)
        rows.append((node["id"], nfast, t_fast, nslow, t_slow))
        fast += t_fast
        slow += t_slow
    # cycle time: every fast read + share of slow reads
    cycle = fast + slow / 10.0
    return rows, cycle, cycle / 0.100

# -------------------------------------------------------------------- emitters
def c_header_node(m, max_points):
    """return text of regmap_node.h."""
    n = m["node"]
    L = [f"/* {BANNER} */", f"/* Register map version {m['meta']['version']}, {m['meta']['date']}. */",
         "#ifndef REGMAP_NODE_H", "#define REGMAP_NODE_H", "",
         f"#define REGMAP_VERSION \"{m['meta']['version']}\"",
         f"#define REGMAP_SEG1_BAUD {m['segments']['seg1']['baud']}u", "",
         "/* Slave addresses */"]
    for node in m["nodes"]:
        L.append(f"#define REG_ADDR_{node['name']} {node['address']}u")
    L += ["", "/* Input registers: health block */"]
    for h in n["health"]:
        L.append(f"#define IR_HLTH_{h['name']} {h['addr']}u /* {h['type']}: {h['desc']} */")
    L += ["", "/* HLTH.STATUS bits */"]
    for b in n["status_bits"]:
        L.append(f"#define HLTH_STATUS_{b['name']} (1u << {b['bit']}) /* {b['desc']} */")
    L += ["", "/* Input registers: one block per measurement point */",
          f"#define IR_POINT_BASE {n['point_base']}u",
          f"#define IR_POINT_BLOCK {n['point_block']}u",
          f"#define REG_MAX_POINTS {max_points}u",
          "#define IR_POINT(p, off) (IR_POINT_BASE + (p) * IR_POINT_BLOCK + (off))"]
    for f in n["point_fields"]:
        if f["type"] != "f32" or f["offset"] % 2:
            raise MapError(f"point field {f['qty']} must be a float32 at an even offset")
        L.append(f"#define PT_OFF_{f['qty']} {f['offset']}u /* float32, {f['unit'] or 'no unit'} */")
    L.append(f"#define PT_FIELDS {len(n['point_fields'])}u")
    L.append("#define PT_FIELD(off) ((off) / 2u) /* index of a field in the point's array of values */")
    e = n["energy_field"]
    L += ["", "/* Input registers: slow block, polled at 1 Hz: firmware version, one reserved",
          "   register that reads 0, and the energy counters (uint32) */",
          f"#define IR_SLOW_BASE {n['slow_base']}u",
          f"#define IR_ENERGY_BASE {n['energy_base']}u",
          "#define IR_ENERGY(p) (IR_ENERGY_BASE + 2u * (p))",
          f"#define PT_COUNTS_PER_E {round(1 / e['scale'])}",
          "", "/* Holding registers */"]
    for h in n["holding"]:
        L.append(f"#define HR_{h['name']} {h['addr']}u /* {h['type']}: {h['desc']} */")
    for b in n["ctrl_bits"]:
        L.append(f"#define CTRL_{b['name']} (1u << {b['bit']}) /* {b['desc']} */")
    L += ["", "/* Calibration: float32 gain then offset per channel;",
          "   channel = 2 * point + (0 voltage, 1 current) */",
          f"#define HR_CAL_BASE {n['cal_base']}u",
          f"#define REG_CAL_CHANNELS {n['cal_channels']}u"]
    for f in n["cal_fields"]:
        L.append(f"#define HR_CAL_{f['name']}(ch) (HR_CAL_BASE + 4u * (ch) + {f['offset']}u)")
    L += ["", "/* Point indices and 10 Hz read sizes by node */"]
    for node in m["nodes"]:
        for i, p in enumerate(node["points"]):
            L.append(f"#define PT_{node['name']}_{p['name']} {i}u /* {p['mp']}, {p['tier']}, {p['kind']} */")
        L.append(f"#define REG_{node['name']}_POINTS {len(node['points'])}u")
        L.append(f"#define REG_{node['name']}_FAST_READ {fast_read_count(m, node)}u")
        L.append(f"#define REG_{node['name']}_SLOW_READ {slow_read_count(m, node)}u")
    L += ["", "#endif /* REGMAP_NODE_H */", ""]
    return "\n".join(L)

def c_header_lcu(m):
    """return text of regmap_lcu.h."""
    lcu = m["lcu"]
    L = [f"/* {BANNER} */", f"/* Register map version {m['meta']['version']}, {m['meta']['date']}. */",
         "#ifndef REGMAP_LCU_H", "#define REGMAP_LCU_H", "",
         f"#define REGMAP_SEG2_BAUD {m['segments']['seg2']['baud']}u",
         f"#define REG_ADDR_LCU {lcu['address']}u",
         f"#define LCU_CONTACTS {lcu['contacts']}u",
         f"#define LCU_CONTACT_MASK 0x{(1 << lcu['contacts']) - 1:04X}u", ""]
    for r in lcu["holding"]:
        L.append(f"#define LCU_HR_{r['name']} {r['addr']}u /* {r['tag']}: {r['desc']} */")
    for r in lcu["input"]:
        L.append(f"#define LCU_IR_{r['name']} {r['addr']}u /* {r['tag']}: {r['desc']} */")
    L.append(f"#define LCU_IR_FIRST {min(r['addr'] for r in lcu['input'])}u")
    L.append(f"#define LCU_IR_COUNT {len(lcu['input'])}u")
    for b in lcu["fault_bits"]:
        L.append(f"#define LCU_FAULT_{b['name']} (1u << {b['bit']}) /* {b['desc']} */")
    L += ["", "#endif /* REGMAP_LCU_H */", ""]
    return "\n".join(L)

def markdown(m, taglist):
    """return text of register_map.md."""
    n = m["node"]
    L = [f"<!-- {BANNER} -->", f"# SGTB register map, version {m['meta']['version']} ({m['meta']['date']})", "",
         "Addresses are zero-based Modbus PDU addresses. Multi-register values are big-endian in word order.",
         "A measured quantity is an IEEE 754 float32 in engineering units.", "",
         "## Node registers (ICD-2), identical on every node", "",
         "| Table | Address | Name | Type | Scale and unit | Rate | Description |",
         "| --- | --- | --- | --- | --- | --- | --- |"]

    def span(a, t):
        """return address span of value, as text."""
        w = WORDS[t]
        return f"{a}" if w == 1 else f"{a} to {a + w - 1}"

    def health_rows(slow):
        """append table rows of health regs inside, or outside, slow block."""
        for h in n["health"]:
            if (h["addr"] >= n["slow_base"]) == slow:
                rate = f"{h['rate_hz']} Hz" if h["rate_hz"] else "1 Hz read"
                L.append(f"| IR | {span(h['addr'], h['type'])} | HLTH.{h['name']} | {h['type']} | {h.get('unit', '')} | {rate} | {h['desc']} |")

    health_rows(False)
    for f in n["point_fields"]:
        L.append(f"| IR | {n['point_base']} + {n['point_block']}p + {span(f['offset'], f['type'])} | point p {f['qty']} | {f['type']} | {f['unit']} | 10 Hz | {f['desc']} |")
    health_rows(True)
    L.append(f"| IR | {n['slow_base'] + 1} | reserved | u16 | | 1 Hz read | Reads 0 |")
    e = n["energy_field"]
    L.append(f"| IR | {n['energy_base']} + 2p, two registers | point p E | {e['type']} | {e['scale']} {e['unit']} | 1 Hz | {e['desc']} |")
    for h in n["holding"]:
        L.append(f"| HR | {span(h['addr'], h['type'])} | {h['name']} | {h['type']} | {h.get('unit', '')} | on command | {h['desc']} |")
    last = n["cal_base"] + 4 * n["cal_channels"] - 1
    L.append(f"| HR | {n['cal_base']} to {last} | CAL gain, offset per channel | f32 x2 | | on command | Channel c at {n['cal_base']} + 4c; c = 2p + (0 voltage, 1 current) |")
    L += ["", "## Nodes and points", "", "| Node | Slave address | Point index | Point | MP | Tier | 10 Hz read (registers) |",
          "| --- | --- | --- | --- | --- | --- | --- |"]
    for node in m["nodes"]:
        for i, p in enumerate(node["points"]):
            L.append(f"| {node['id']} | {node['address']} | {i} | {p['name']} | {p['mp']} | {p['tier']} | {fast_read_count(m, node)} |")
    lcu = m["lcu"]
    L += ["", f"## Load control unit (ICD-6), slave address {lcu['address']}", "",
          "| Table | Address | Tag | Type | Description |", "| --- | --- | --- | --- | --- |"]
    for r in lcu["holding"]:
        L.append(f"| HR | {r['addr']} | {r['tag']} | {r['type']} | {r['desc']} |")
    for r in lcu["input"]:
        L.append(f"| IR | {r['addr']} | {r['tag']} | {r['type']} | {r['desc']} |")
    L += ["", "## Segment 1 bus budget (CAP-M4-34, ceiling 50%)", "",
          "| Configuration | Cycle time (ms) | Utilization |", "| --- | --- | --- |"]
    for label, br in (("Demo 2: NODE-SRC and NODE-SY1", 1), ("Full bench: five nodes", None)):
        _, cyc, util = bus_budget(m, br)
        L.append(f"| {label} | {cyc * 1e3:.1f} | {util * 100:.1f}% |")
    L += ["", f"## Tag list ({len(taglist)} tags)", "",
          "| Tag | Slave | Table | Address | Type | Scale | Unit | Rate (Hz) | MP |",
          "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for t in taglist:
        L.append(f"| {t['tag']} | {t['slave']} | {t['table']} | {t['addr']} | {t['type']} | {t['scale']} | {t['unit']} | {t['rate_hz']} | {t['mp'] or ''} |")
    return "\n".join(L) + "\n"

def build():
    """return text of every generated file, tag count, cycle time, and utilization."""
    m = load()
    max_points = node_layout(m)
    taglist = tags(m)
    _, cycle, util = bus_budget(m)
    if util > 0.50:
        raise MapError(f"segment 1 utilization {util * 100:.1f}% exceeds the 50% ceiling of CAP-M4-34")
    poll = {node["id"]: dict(slave=node["address"], fast_count=fast_read_count(m, node),
                             slow_addr=m["node"]["slow_base"], slow_count=slow_read_count(m, node),
                             energy_addr=m["node"]["energy_base"])
            for node in m["nodes"]}
    files = {
        "regmap_node.h": c_header_node(m, max_points),
        "regmap_lcu.h": c_header_lcu(m),
        "tags.json": json.dumps(dict(banner=BANNER, version=m["meta"]["version"], date=m["meta"]["date"],
                                     word_order="big", segments=m["segments"], poll=poll,
                                     tags=taglist), indent=1) + "\n",
        "register_map.md": markdown(m, taglist),
    }
    return files, len(taglist), cycle, util

def main():
    """write generated files, or check them when --check is given; return exit code."""
    check = "--check" in sys.argv
    try:
        files, ntags, cycle, util = build()
    except MapError as e:
        print(f"regmap error: {e}", file=sys.stderr)
        return 2
    stale = []
    OUT.mkdir(exist_ok=True)
    for name, text in files.items():
        path = OUT / name
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            path.write_text(text, encoding="utf-8")
    if stale:
        print("generated/ is out of date: " + ", ".join(stale), file=sys.stderr)
        return 1
    print(f"{ntags} tags; segment 1 cycle {cycle * 1e3:.1f} ms, {util * 100:.1f}% of 100 ms")
    return 0

if __name__ == "__main__":
    sys.exit(main())
